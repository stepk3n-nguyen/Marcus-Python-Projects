# 1. LỆNH XUẤT DỮ LIỆU: print()
# ----------------------------------------------------
print("=== CHÀO MỪNG BẠN ĐẾN VỚI LỚP HỌC PYTHON & AI! ===")
print("Xin chào! Tôi là máy tính, người bạn lập trình của bạn.")

